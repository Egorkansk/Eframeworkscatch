Start();//функция начала добавления объектов (Immediate mode) это когда объекты добавляются каждый кадр, но они кэшируются для оптимизации
  //добавляем Scrollbox на весь экран их можно добавлять сколько угодно для прокрутки интерфейса, скролоинга игроаого поля или картинки
  Addscrollbox(0,0,w,h);  //w h это ширина высота экрана
  let scr=etot;           // etot указатель на последний добавленный объект
  // Если картинка загружена — показываем канвас
  if(can){
    Addcanvas(can,0,0,plan.width,plan.height);
    if(mousedown(etot)){
      drawing=true;
      can.ctx.beginPath();
      can.ctx.moveTo(mx,my); //рисуем на относительных координатах(относительно etot т.е canvas) есть еще абсолютные координаты xx yy
    }
    if(mousedrag(etot)&&drawing){
      can.ctx.lineTo(mx,my);//рисуем на относительных координатах(относительно etot т.е canvas) есть еще movex movey это значения сдвига в пикселях с учтенным масштабированием и скроллом
      can.ctx.stroke(); // рисуем сразу
    }
    if(mouseup(etot)) drawing=false;
  }
  //автоматическая обработка скролла, зума и блокирование при пнреходе вне области экрана
  Scrolling();Zooming();Blockscroll();
  // Кнопка "Открыть" поверх всего
  Addoverlay(0,0,w,h);//оверлей это такой объект(контейнер) как скроллбокс но не скроллится и поверх него добавляются новые объекты
  Addtbutton("Открыть",20,20,20+wd*3,20+wd);  //wd это переменная равная 1/10 большей стороны экрана для привязки размеров объектов
  if(clicked()){//событие клика не путать с mousedown
    let r=await openImagePicker();//вспомогательная функция возвращает открываемое изображение
    if(r){
      plan=r.img;
      // Создаём канвас под размер картинки
      can=Newcanvas(plan.width,plan.height);
      // Рисуем картинку на канвасе
      can.ctx.drawImage(plan,0,0);
      scrollboxto(scr,plan.width/2,plan.height/2,plan.width*0.4,plan.height*0.4);
      //плавно перемещаем скролл
    }
  }
  draw();
  
  